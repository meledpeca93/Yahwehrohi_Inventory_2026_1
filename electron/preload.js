const { contextBridge, ipcRenderer } = require('electron');

let sessionToken='';
async function invoke(channel,...args){
 try { sessionToken=JSON.parse(localStorage.getItem('yahweh-rohi-session-user')||'null')?.sessionToken || sessionToken; } catch {}
 const result=await ipcRenderer.invoke(channel,...args,...(['auth:login','auth:users','db:health'].includes(channel)?[]:[{sessionToken}]));
 if(channel==='auth:login')sessionToken=result.user.sessionToken;
 return result;
}
