const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('electronAPI', {
  health: () => ipcRenderer.invoke('db:health'),
  login: (credentials) => ipcRenderer.invoke('auth:login', credentials),
  getUsers: () => ipcRenderer.invoke('auth:users'),
  getAttendanceUsers: () => ipcRenderer.invoke('attendance:list'),
  saveAttendanceMark: (payload) => ipcRenderer.invoke('attendance:save-mark', payload),
  getCustomers: () => ipcRenderer.invoke('customers:list'),
  getSuppliers: () => ipcRenderer.invoke('suppliers:list'),
  getExpiringProducts: () => ipcRenderer.invoke('products:expiring'),
  getPurchases: () => ipcRenderer.invoke('purchases:list'),
  getCredits: () => ipcRenderer.invoke('credits:list'),
  createCreditPayment: (payload) => ipcRenderer.invoke('credits:payment-create', payload),
  getNextInvoiceNumber: () => ipcRenderer.invoke('invoices:next'),
  getInvoices: () => ipcRenderer.invoke('invoices:list'),
  getTodayInvoices: () => ipcRenderer.invoke('invoices:today'),
  getDailyCuts: (dateFrom, dateTo, userId) => ipcRenderer.invoke('daily-cuts:list', { dateFrom, dateTo, userId }),
  previewDailyCut: (date, userId) => ipcRenderer.invoke('daily-cuts:preview', { date, userId }),
  createDailyCut: (payload) => ipcRenderer.invoke('daily-cuts:create', payload),
  createOpeningCut: (payload) => ipcRenderer.invoke('daily-cuts:opening', payload),
  getCreditPayments: (date, userId) => ipcRenderer.invoke('credit-payments:list', { date, userId }),
  closeApp: () => ipcRenderer.invoke('app:quit'),
  getInvoicesSummary: () => ipcRenderer.invoke('invoices:summary'),
  getInvoiceDetails: (invoiceId) => ipcRenderer.invoke('invoices:details', invoiceId),
  annulInvoice: (invoiceId) => ipcRenderer.invoke('invoices:annul', invoiceId),
  activateInvoice: (invoiceId) => ipcRenderer.invoke('invoices:activate', invoiceId),
  getDashboardSalesSummary: () => ipcRenderer.invoke('dashboard:sales-summary'),
  getDashboardSalesTrend: (period) => ipcRenderer.invoke('dashboard:sales-trend', period),
  getSalesDropAlert: () => ipcRenderer.invoke('dashboard:sales-drop-alert'),
  getCostSalesPeriodTotal: (year, month) => ipcRenderer.invoke('costs:sales-period-total', { year, month }),
  getCostSalesByCategory: (year, month) => ipcRenderer.invoke('costs:sales-by-category', { year, month }),
  getCostIncreaseAlerts: () => ipcRenderer.invoke('costs:cost-increase-alerts'),
  getOperationalCosts: (year, month) => ipcRenderer.invoke('costs:operational-list', { year, month }),
  createOperationalCost: (payload) => ipcRenderer.invoke('costs:operational-create', payload),
  getAuditHistory: (limit) => ipcRenderer.invoke('history:audit', limit),
  getProducts: () => ipcRenderer.invoke('products:list'),
  updateInventoryStockLevels: (payload) => ipcRenderer.invoke('products:update-inventory', payload),
  createSale: (payload) => ipcRenderer.invoke('sales:create', payload),
  createPurchase: (payload) => ipcRenderer.invoke('purchases:create', payload),
  processPurchaseInvoiceOcr: (payload) => ipcRenderer.invoke('purchases:ocr-invoice', payload),
});
