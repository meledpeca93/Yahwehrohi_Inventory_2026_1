IF OBJECT_ID('dbo.PRODUCTO_LOTE', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.PRODUCTO_LOTE (
    ID_LOTE INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    ID_PRODUCTO INT NOT NULL,
    CODIGO_PRODUCTO VARCHAR(120) NOT NULL,
    NUM_LOTE VARCHAR(80) NOT NULL,
    FECHA_INGRESO DATE NOT NULL,
    FECHA_VENCIMIENTO DATE NULL,
    CANTIDAD_INICIAL DECIMAL(18, 2) NOT NULL,
    CANTIDAD_DISPONIBLE DECIMAL(18, 2) NOT NULL,
    COSTO_UNITARIO DECIMAL(18, 4) NOT NULL,
    ID_COMPRA INT NULL,
    TABLA_COMPRA VARCHAR(80) NULL,
    NUM_FACT VARCHAR(80) NULL,
    ESTADO VARCHAR(20) NOT NULL CONSTRAINT DF_PRODUCTO_LOTE_ESTADO DEFAULT 'ACTIVO',
    ORIGEN VARCHAR(40) NOT NULL CONSTRAINT DF_PRODUCTO_LOTE_ORIGEN DEFAULT 'COMPRA',
    CREADO_POR VARCHAR(120) NULL,
    CREADO_EN DATETIME2 NOT NULL CONSTRAINT DF_PRODUCTO_LOTE_CREADO_EN DEFAULT SYSDATETIME(),
    ACTUALIZADO_EN DATETIME2 NULL
  );

  CREATE INDEX IX_PRODUCTO_LOTE_FEFO
    ON dbo.PRODUCTO_LOTE (ID_PRODUCTO, ESTADO, FECHA_VENCIMIENTO, FECHA_INGRESO, ID_LOTE)
    INCLUDE (CANTIDAD_DISPONIBLE);

  CREATE INDEX IX_PRODUCTO_LOTE_CODIGO
    ON dbo.PRODUCTO_LOTE (CODIGO_PRODUCTO, NUM_LOTE);
END;
GO

