INSERT INTO dbo.PRODUCTO_LOTE (
  ID_PRODUCTO,
  CODIGO_PRODUCTO,
  NUM_LOTE,
  FECHA_INGRESO,
  FECHA_VENCIMIENTO,
  CANTIDAD_INICIAL,
  CANTIDAD_DISPONIBLE,
  COSTO_UNITARIO,
  ID_COMPRA,
  TABLA_COMPRA,
  NUM_FACT,
  ESTADO,
  ORIGEN,
  CREADO_POR
)
SELECT
  p.id_producto,
  p.codigo,
  CONCAT('INICIAL-', p.codigo),
  CAST(GETDATE() AS DATE),
  TRY_CONVERT(DATE, i.FECHA_VENCIMIENTO),
  CAST(ISNULL(i.stock, 0) AS DECIMAL(18, 2)),
  CAST(ISNULL(i.stock, 0) AS DECIMAL(18, 2)),
  CAST(ISNULL(i.precio_costo, 0) AS DECIMAL(18, 4)),
  NULL,
  NULL,
  'MIGRACION_INVENTARIO',
  CASE WHEN ISNULL(i.stock, 0) > 0 THEN 'ACTIVO' ELSE 'AGOTADO' END,
  'MIGRACION_INVENTARIO',
  'FEFO_INICIAL'
FROM dbo.producto p
INNER JOIN dbo.inventario i
  ON i.id_inventario = p.id_producto
WHERE p.activo = 1
  AND ISNULL(i.stock, 0) > 0
  AND NOT EXISTS (
    SELECT 1
    FROM dbo.PRODUCTO_LOTE l
    WHERE l.ID_PRODUCTO = p.id_producto
      AND l.ORIGEN = 'MIGRACION_INVENTARIO'
  );
GO
